// Builds docs/TEST_CASES.md from the automated tests, so the catalog always matches what runs.
//   node tests/catalog.mjs
import fs from "node:fs";
const root = new URL("../../", import.meta.url);
const e2e = fs.readFileSync(new URL("web/tests/e2e.mjs", root), "utf8").split("\n");
const sections = [];
let cur = { name: "Setup", checks: [] };
for (const line of e2e) {
  const sec = line.match(/^ {2}\/\/ (.+)/);
  if (sec && !/^(eslint|\w+:)/.test(sec[1])) { if (cur.checks.length) sections.push(cur); const nm = sec[1].replace(/^Use case: /, "").replace(/[.:]$/, ""); cur = { name: nm[0].toUpperCase() + nm.slice(1), checks: [] }; continue; }
  for (const m of line.matchAll(/check\((["`])((?:(?!\1)[^\\]|\\.)+)\1/g)) cur.checks.push(m[2].replace(/\\(.)/g, "$1").replace(/\$\{[^}]+\}/g, "…"));
}
if (cur.checks.length) sections.push(cur);
const py = fs.readdirSync(new URL("tests/", root)).filter((f) => /^test_.*\.py$/.test(f)).flatMap((f) =>
  [...fs.readFileSync(new URL(`tests/${f}`, root), "utf8").matchAll(/^def (test_\w+)/gm)].map((m) => `${f.replace(/\.py$/, "")} · ${m[1].replace(/^test_/, "").replace(/_/g, " ")}`));
const logic = [...fs.readFileSync(new URL("web/tests/logic.test.ts", root), "utf8").matchAll(/^\/\/ (.+)$/gm)].map((m) => m[1]).filter((l) => !l.startsWith("Unit tests"));
let n = 0;
const out = [`# Use cases & test cases

Generated by \`node web/tests/catalog.mjs\` from the automated tests — every row below runs on each pull request
(GitHub Actions: *build-and-e2e* and *test*). Totals: **${sections.reduce((s, x) => s + x.checks.length, 0)} end-to-end checks** (real website + PostgreSQL
with stand-in YouTube, AI, Apify, Telegram, Google and GitHub services), **${py.length} worker tests**, **${logic.length} logic test groups**.

## How to run
\`\`\`
python -m ytanalytics init-db            # with DATABASE_URL pointing at a test database
cd web && npx next build && node tests/e2e.mjs
node --experimental-strip-types tests/logic.test.ts
python -m pytest -q                      # from the repository root
\`\`\`

## End-to-end use cases
`];
for (const s of sections) {
  out.push(`\n### ${s.name}\n\n| ID | Test case |\n|---|---|`);
  for (const c of s.checks) out.push(`| E${String(++n).padStart(3, "0")} | ${c.replace(/\|/g, "\\|")} |`);
}
out.push(`\n## Logic (unit) tests\n`, ...logic.map((l) => `- ${l}`));
out.push(`\n## Worker (Python) tests\n`, ...py.map((t) => `- ${t}`));
out.push(`\n## UI/UX checks (run with each redesign)

| ID | Check | How |
|---|---|---|
| U01 | Every page fits a 390 px iPhone 13 screen (no sideways scroll) | Playwright iPhone 13 walk-through of all pages |
| U02 | No page errors or hydration mismatches in the browser | Same walk-through, console and page-error capture |
| U03 | Every page renders at 1440 px desktop width | Desktop walk-through with full-page screenshots |
| U04 | Notch and home-bar safe areas in the home-screen app | viewport-fit=cover, safe-area padding on top bar and bottom menu |
| U05 | Relative times ("12s ago", countdowns) render only on the device | Server/browser text match (no React #418) |
| U06 | Channel switcher scopes every page; competitors never become the focus | e2e checks above + manual pass |
| U07 | One accent colour, sentiment colours only for sentiment, serif only for titles | Design review of screenshots |
`);
fs.writeFileSync(new URL("docs/TEST_CASES.md", root), out.join("\n") + "\n");
console.log(`docs/TEST_CASES.md: ${n} e2e cases, ${logic.length} logic groups, ${py.length} worker tests`);
